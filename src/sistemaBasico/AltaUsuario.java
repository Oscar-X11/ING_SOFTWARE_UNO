    //5.- metodo que captura los datos del forumularo y los guarda en la bd
    public void capturaGuardaDatos() {
        // 1. Capturar información
        String nombre = campoNombre.getText();
        String aP = campoApPat.getText();
        String aM = campoApMat.getText();
        String telefono = campoTelefono.getText();
        String email = campoEmail.getText();
        String estado_civil = menuEstCivil.getSelectedItem().toString();

        int hijos = 0;
        if (radioSi.isSelected()) {
            hijos = 1;
        } else if (radioNo.isSelected()) {
            hijos = 0;
        }

        String intereses = "";
        if (jCheckLibros.isSelected()) {
            intereses += "Libros ";
        }
        if (jCheckDeportes.isSelected()) {
            intereses += "Deportes ";
        }
        if (jCheckMusica.isSelected()) {
            intereses += "Musica ";
        }
        if (jCheckOtros.isSelected()) {
            intereses += "Otros ";
        }
        intereses = intereses.trim(); // Quita el último espacio sobrante

// 2. Preparar la consulta para guardar los datos en la base de datos
        // 2. Preparar la consulta para guardar los datos en la base de datos
        try {
            String sql = "INSERT INTO empleados (nombre, apellidop, apellidom, telefono, correo, estado_civil, hijos, intereses) VALUES (?,?,?,?,?,?,?,?)";
            pps = cn.prepareStatement(sql);

            pps.setString(1, nombre);
            pps.setString(2, aP);
            pps.setString(3, aM);
            pps.setString(4, telefono);
            pps.setString(5, email);
            pps.setString(6, estado_civil);
            pps.setInt(7, hijos);
            pps.setString(8, intereses);

            // 3. Ejecutar la consulta y avisar al usuario
            pps.executeUpdate();
            JOptionPane.showMessageDialog(null, "Datos guardados correctamente");
            limpiaCaampo();

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Error al guardar los datos: " + ex.getMessage());
        }
    }

